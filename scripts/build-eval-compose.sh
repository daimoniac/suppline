#!/bin/sh
# Writes the self-contained zero-credential eval Compose file to stdout.
#
# The file needs no checkout and no build: the demo config and the helper
# scripts are inlined as Compose `configs`, and suppline comes from GHCR.
# The release workflow runs this with the release version and attaches the
# result to the GitHub Release as docker-compose.eval.yml.
#
# Usage:
#   scripts/build-eval-compose.sh [VERSION] > docker-compose.eval.yml
#   SUPPLINE_VERSION=VERSION docker compose -f docker-compose.eval.yml up -d
#
# Needs Docker Compose 2.23.1 or newer (inline config content).

set -eu

cd "$(dirname "$0")/.."
VERSION=${1:-latest}

# Compose interpolates $ in inline content, so escape it. Indent for the block.
emit_config() {
    printf '  %s:\n    content: |\n' "$1"
    sed -e 's/\$/$$/g' -e 's/^/      /' "$2"
}

cat <<EOF
# Zero-credential suppline eval. Self-contained: no checkout, no build.
# Throwaway registry and demo policies. Not for production.
#
#   docker compose -f docker-compose.eval.yml up -d
#   open http://localhost:8080   (API key: demo)
#   docker compose -f docker-compose.eval.yml --profile eval-gate run --rm eval-gate
#
# Generated by scripts/build-eval-compose.sh for suppline ${VERSION}.
# Docs: https://suppline.cloud/EVAL.html
name: suppline-eval

services:
  registry:
    image: registry:3.1.2
    environment:
      - REGISTRY_STORAGE_DELETE_ENABLED=true
    volumes:
      - registry-data:/var/lib/registry
    ports:
      - "127.0.0.1:\${SUPPLINE_REGISTRY_PORT:-5000}:5000"
    restart: unless-stopped
    healthcheck:
      test: ["CMD", "wget", "--no-verbose", "--tries=1", "--spider", "http://localhost:5000/v2/"]
      interval: 10s
      timeout: 5s
      retries: 5
      start_period: 5s

  postgres:
    image: postgres:18-alpine
    environment:
      POSTGRES_DB: suppline
      POSTGRES_USER: suppline
      POSTGRES_PASSWORD: suppline
    volumes:
      - postgres-data:/var/lib/postgresql
    restart: unless-stopped
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U suppline -d suppline"]
      interval: 5s
      timeout: 5s
      retries: 10

  trivy:
    image: aquasec/trivy:0.76.2
    entrypoint: ["/bin/sh", "/trivy-json-logs.sh"]
    command: ["server", "--listen", "0.0.0.0:4954"]
    environment:
      - TRIVY_CACHE_DIR=/trivy-cache
    volumes:
      - trivy-cache:/trivy-cache
    configs:
      - source: trivy_json_logs
        target: /trivy-json-logs.sh
    restart: unless-stopped
    healthcheck:
      test: ["CMD", "wget", "--no-verbose", "--tries=1", "--spider", "http://localhost:4954/healthz"]
      interval: 30s
      timeout: 10s
      retries: 3
      start_period: 30s

  suppline:
    image: ghcr.io/daimoniac/suppline:\${SUPPLINE_VERSION:-${VERSION}}
    user: "0:0"
    depends_on:
      registry:
        condition: service_healthy
      trivy:
        condition: service_started
      postgres:
        condition: service_healthy
    ports:
      - "\${SUPPLINE_UI_PORT:-8080}:8080"
      - "\${SUPPLINE_METRICS_PORT:-9090}:9090"
    environment:
      - SUPPLINE_CONFIG=/config/suppline.yml
      - SUPPLINE_API_KEY=demo
      - POSTGRES_URL=postgres://suppline:suppline@postgres:5432/suppline?sslmode=disable
      - ATTESTATION_KEY_PASSWORD=demo
      - KEYS_DIR=/keys/demo
    volumes:
      - keys:/keys
    configs:
      - source: suppline_yml
        target: /config/suppline.yml
      - source: suppline_entrypoint
        target: /compose-suppline-entrypoint.sh
    entrypoint: ["/bin/sh", "/compose-suppline-entrypoint.sh"]
    restart: unless-stopped
    healthcheck:
      test: ["CMD", "wget", "--no-verbose", "--tries=1", "--spider", "http://localhost:9090/health"]
      interval: 30s
      timeout: 10s
      retries: 3
      start_period: 15s

  # Attestation gate POC (the same SCAI checks Kyverno makes at admission).
  eval-gate:
    profiles: ["eval-gate"]
    image: ghcr.io/daimoniac/suppline:\${SUPPLINE_VERSION:-${VERSION}}
    user: "0:0"
    depends_on:
      suppline:
        condition: service_healthy
      registry:
        condition: service_healthy
    environment:
      - SUPPLINE_API_URL=http://suppline:8080
      - SUPPLINE_API_KEY=demo
      - EVAL_REGISTRY=registry:5000
      - EVAL_COSIGN_PUBKEY=/keys/demo/cosign.pub
    volumes:
      - keys:/keys:ro
    configs:
      - source: eval_gate
        target: /eval-attestation-gate.sh
    entrypoint: ["/bin/sh", "-c"]
    command:
      - |
        set -eu
        apk add --no-cache curl jq >/dev/null
        exec /bin/sh /eval-attestation-gate.sh

volumes:
  registry-data:
  postgres-data:
  trivy-cache:
  keys:

configs:
EOF
emit_config suppline_yml suppline.demo.yml
emit_config suppline_entrypoint scripts/compose-suppline-entrypoint.sh
emit_config trivy_json_logs scripts/trivy-json-logs.sh
emit_config eval_gate scripts/eval-attestation-gate.sh
