package triage

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"time"

	"github.com/daimoniac/suppline/internal/gitops"
	"github.com/daimoniac/suppline/internal/types"
)

var (
	hostNetworkTrue = regexp.MustCompile(`(?i)hostNetwork:\s*['"]?true\b`)
	privilegedTrue  = regexp.MustCompile(`(?i)privileged:\s*['"]?true\b`)
	hostPathKey     = regexp.MustCompile(`(?i)hostPath:`)
	portLine        = regexp.MustCompile(`(?i)\b(?:containerPort|port):\s*\d+`)
)

type outcome string

const (
	outcomeReject      outcome = "reject"
	outcomeNotAffected outcome = "not_affected"
	outcomeAffected    outcome = "affected"
)

type verdictDecision struct {
	Action    outcome
	Reason    string
	Statement types.VEXStatement
}

func decide(settings Settings, job Job, verdict modelVerdict, evidenceErr string, kev bool, kevErr error, existing *types.VEXStatement, checkouts []gitops.Checkout, triageID string, now time.Time) verdictDecision {
	if settings.BlockKEV && kevErr != nil {
		return flipOrReject(existing, job, "CISA KEV feed unavailable: "+kevErr.Error(), settings, checkouts, triageID, now)
	}
	if settings.BlockKEV && kev {
		return flipOrReject(existing, job, "CVE is listed in the CISA Known Exploited Vulnerabilities catalog", settings, checkouts, triageID, now)
	}

	reason := ""
	switch {
	case verdict.Verdict != "not_affected":
		reason = "model verdict is " + verdict.Verdict
	case verdict.Confidence < settings.MinConfidence:
		reason = fmt.Sprintf("confidence %.2f is below %.2f", verdict.Confidence, settings.MinConfidence)
	case evidenceErr != "":
		reason = evidenceErr
	case len(verdict.Evidence) == 0:
		reason = "not_affected requires evidence"
	default:
		justification := types.NormalizeVEXJustification(types.VEXJustification(verdict.Justification))
		if _, ok := settings.Allowed[justification]; !ok {
			reason = fmt.Sprintf("justification %q is not allowed", verdict.Justification)
			break
		}
		expires := now.Add(settings.Expiry).Unix()
		return verdictDecision{
			Action: outcomeNotAffected,
			Statement: types.VEXStatement{
				ID:            job.CVEID,
				State:         types.VEXStateNotAffected,
				Justification: justification,
				Detail:        provenance(triageID, settings.Model, checkouts, verdict, now),
				ExpiresAt:     &expires,
				Source:        types.VEXSourceAuto,
			},
		}
	}
	return flipOrReject(existing, job, reason+": "+verdict.Reasoning, settings, checkouts, triageID, now)
}

func flipOrReject(existing *types.VEXStatement, job Job, reason string, settings Settings, checkouts []gitops.Checkout, triageID string, now time.Time) verdictDecision {
	if existing == nil || existing.State != types.VEXStateNotAffected {
		return verdictDecision{Action: outcomeReject, Reason: reason}
	}
	expires := now.Add(settings.Expiry).Unix()
	return verdictDecision{
		Action: outcomeAffected,
		Reason: reason,
		Statement: types.VEXStatement{
			ID:        job.CVEID,
			State:     types.VEXStateAffected,
			Detail:    provenance(triageID, settings.Model, checkouts, modelVerdict{Verdict: "affected", Reasoning: reason}, now),
			ExpiresAt: &expires,
			Source:    types.VEXSourceAuto,
		},
	}
}

func provenance(triageID, model string, checkouts []gitops.Checkout, verdict modelVerdict, now time.Time) string {
	var repos []string
	for _, checkout := range checkouts {
		repos = append(repos, checkout.Name+"@"+checkout.SHA)
	}
	var evidence []string
	for _, item := range verdict.Evidence {
		if item.Line < 1 && item.Pattern != "" {
			evidence = append(evidence, fmt.Sprintf("%s:%s:%s", item.Repo, item.Path, item.Pattern))
			continue
		}
		evidence = append(evidence, fmt.Sprintf("%s:%s:%d", item.Repo, item.Path, item.Line))
	}
	text := fmt.Sprintf("auto-generated by suppline triage\ntriage_id: %s\nmodel: %s\ntimestamp: %s\nrepos: %s\nverdict: %s\nevidence: %s\nreasoning: %s",
		triageID, model, now.UTC().Format(time.RFC3339), strings.Join(repos, " "), verdict.Verdict, strings.Join(evidence, "; "), strings.TrimSpace(verdict.Reasoning))
	if len(text) > 4000 {
		text = text[:4000]
	}
	return text
}

func verifyEvidence(roots Roots, pub *publicSource, job Job, verdict *modelVerdict) error {
	if verdict == nil || verdict.Verdict != "not_affected" {
		return nil
	}
	justification := types.NormalizeVEXJustification(types.VEXJustification(verdict.Justification))
	gitopsHits := 0
	publicHits := 0
	absenceHits := 0
	filtered := make([]modelEvidence, 0, len(verdict.Evidence))
	for i, item := range verdict.Evidence {
		if id := strings.TrimSpace(item.GrepID); id != "" {
			hit, ok := pub.grep(id)
			if pub == nil || !ok {
				verdict.Evidence = filtered
				return fmt.Errorf("evidence[%d] grep_id %s was not returned by a public grep", i, id)
			}
			if hit.Empty {
				if !hit.Absence {
					verdict.Evidence = filtered
					return fmt.Errorf("evidence[%d] grep_id %s is not absence", i, id)
				}
				filtered = append(filtered, modelEvidence{
					Repo: hit.Repo, Path: hit.Path, Pattern: hit.Pattern, Commit: hit.Commit, GrepID: hit.ID,
				})
				absenceHits++
				continue
			}
			if len(hit.Rows) == 0 {
				verdict.Evidence = filtered
				return fmt.Errorf("evidence[%d] grep_id %s returned no citable lines", i, id)
			}
			for _, row := range hit.Rows {
				filtered = append(filtered, modelEvidence{
					Repo: hit.Repo, Path: row.Path, Line: row.Line, Quote: row.Text, GrepID: hit.ID,
				})
				publicHits++
			}
			continue
		}
		if strings.TrimSpace(item.Quote) == "" && strings.TrimSpace(item.Pattern) != "" {
			continue
		}
		if strings.TrimSpace(item.Quote) == "" || item.Line < 1 || strings.TrimSpace(item.Path) == "" {
			verdict.Evidence = filtered
			return fmt.Errorf("evidence[%d] needs repo, path, line, and quote", i)
		}
		line, fromPublic := "", false
		if pub != nil {
			if text, ok := pub.line(item.Repo, item.Path, item.Line); ok {
				line, fromPublic = text, true
			}
		}
		if !fromPublic {
			got, err := roots.Line(item.Repo, item.Path, item.Line)
			if err != nil {
				verdict.Evidence = filtered
				return fmt.Errorf("evidence[%d]: %w", i, err)
			}
			line = got
			gitopsHits++
		} else {
			publicHits++
		}
		if !strings.Contains(line, strings.TrimSpace(item.Quote)) && !strings.Contains(strings.TrimSpace(item.Quote), strings.TrimSpace(line)) {
			verdict.Evidence = filtered
			return fmt.Errorf("evidence[%d] quote does not match %s:%d", i, item.Path, item.Line)
		}
		filtered = append(filtered, item)
	}
	verdict.Evidence = filtered
	if justification == types.VEXJustCodeNotReachable {
		if publicHits > 0 || absenceHits > 0 {
			return nil
		}
		if kernelPackage(job.PackageName) {
			return verifyKernelWorkload(roots, job, *verdict)
		}
		return fmt.Errorf("code_not_reachable requires a public line or an empty grep of a public checkout")
	}
	if justification == types.VEXJustRequiresConfiguration || justification == types.VEXJustRequiresEnvironment {
		if gitopsHits == 0 && publicHits == 0 {
			return fmt.Errorf("%s requires a gitops or public checkout line", justification)
		}
		return nil
	}
	if gitopsHits == 0 {
		return fmt.Errorf("%s requires a gitops checkout line", justification)
	}
	return nil
}

func verifyKernelWorkload(roots Roots, job Job, verdict modelVerdict) error {
	if strings.TrimSpace(job.Repository) == "" {
		return fmt.Errorf("kernel workload needs the image repository")
	}
	named := false
	for _, item := range verdict.Evidence {
		if strings.TrimSpace(item.Quote) == "" {
			continue
		}
		if _, err := roots.Line(item.Repo, item.Path, item.Line); err != nil {
			continue
		}
		if strings.Contains(item.Quote, job.Repository) || (portLine.MatchString(item.Quote) && evidenceFileContains(roots, item, job.Repository)) {
			named = true
			break
		}
	}
	if !named {
		return fmt.Errorf("kernel workload needs a gitops line that names the image or its port")
	}
	found, blocked := scanWorkload(roots, job.Repository)
	if !found {
		return fmt.Errorf("no matching workload file")
	}
	if blocked {
		return fmt.Errorf("workload sets hostNetwork, privileged, or a host device")
	}
	return nil
}

func evidenceFileContains(roots Roots, item modelEvidence, repository string) bool {
	root, err := roots.checkout(item.Repo)
	if err != nil || root.Public {
		return false
	}
	full, err := safePath(root.Dir, item.Path)
	if err != nil {
		return false
	}
	raw, err := os.ReadFile(full)
	return err == nil && strings.Contains(string(raw), repository)
}

func scanWorkload(roots Roots, repository string) (found, blocked bool) {
	for _, checkout := range roots.Checkouts {
		if checkout.Public || checkout.Dir == "" {
			continue
		}
		_ = filepath.WalkDir(checkout.Dir, func(full string, d os.DirEntry, walkErr error) error {
			if walkErr != nil || d.IsDir() {
				if d != nil && d.IsDir() && d.Name() == ".git" {
					return filepath.SkipDir
				}
				return nil
			}
			name := strings.ToLower(d.Name())
			if !strings.HasSuffix(name, ".yaml") && !strings.HasSuffix(name, ".yml") {
				return nil
			}
			info, err := d.Info()
			if err != nil || info.Size() > 1<<20 {
				return nil
			}
			raw, err := os.ReadFile(full)
			if err != nil || !strings.Contains(string(raw), repository) {
				return nil
			}
			found = true
			text := string(raw)
			if hostNetworkTrue.MatchString(text) || privilegedTrue.MatchString(text) || hostPathKey.MatchString(text) {
				blocked = true
			}
			return nil
		})
	}
	return found, blocked
}
